def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='reject stale generated bindings')
    args = parser.parse_args()
    try:
        # Validate/render the entire closed set before writing any file; a bad
        # later schema cannot partially update an earlier contract.
        generated = [
            (OUTPUT, render(SOURCE.read_bytes())),
            (CAP_OUTPUT, render_cap(CAP_SOURCE.read_bytes())),
            (PROVIDER_OUTPUT, render_provider(PROVIDER_SOURCE.read_bytes())),
            (APP_DATA_OUTPUT, render_app_data(APP_DATA_SOURCE.read_bytes())),
        ]
        if args.check:
            for output, text in generated:
                if not output.is_file() or output.read_text() != text:
                    raise ValueError(f'generated {output.stem} bindings are stale; run python3 tools/idl/generate.py')
            print('PASS: generated closed bindings match their separate schemas and generator')
        else:
            for output, text in generated:
                output.write_text(text)
                print(f'Generated {output.relative_to(ROOT)}')
    except (OSError, ValueError, TypeError) as error:
        print(f'FAIL: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
