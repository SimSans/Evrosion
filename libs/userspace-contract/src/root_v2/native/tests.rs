#[test]
fn native_exact22_roundtrip_has_identical_base_roles_and_explicit_extras() {
    let bytes = fixture();
    let value = FullGraph::parse(&bytes).unwrap();
    let actual = value.context();
    let expected = context();
    assert_eq!(
        (
            actual.epoch,
            actual.incarnation,
            actual.process,
            actual.limits,
            actual.manifest,
            actual.authority
        ),
        (
            expected.epoch,
            expected.incarnation,
            expected.process,
            expected.limits,
            expected.manifest,
            expected.authority
        )
    );
    assert_eq!(value.bytes(), bytes);
    for (i, role) in root_v2::ROLES.iter().enumerate() {
        assert_eq!(value.handle(role.role), 100 + i as u64);
        assert_eq!(
            (ROLES[i].selector, ROLES[i].kind, ROLES[i].rights),
            (role.role.selector(), role.kind, role.rights)
        );
    }
    for (extra, handle, rights) in [
        (ExtraRole::AppBImage, 118, 1),
        (ExtraRole::PackageA, 119, 229),
        (ExtraRole::PackageB, 120, 229),
        (ExtraRole::BadShellImage, 121, 1),
    ] {
        assert_eq!(value.extra(extra), handle);
        let actual = value
            .grants()
            .find(|g| g.selector == extra.selector())
            .unwrap();
        assert_eq!((actual.kind, actual.rights), (1, rights));
    }
    assert!(root_v2::Bootstrap::parse(&bytes).is_err());
    assert!(root_v2::FullGraph::parse(&bytes).is_err());
    assert!(crate::Bootstrap::parse(&bytes).is_err());
    let desktop =
        root_v2::encode_full_graph(context(), core::array::from_fn(|i| 100 + i as u64)).unwrap();
    assert!(Bootstrap::parse(&desktop).is_err());
}
#[test]
fn native_length_header_every_reserved_byte_and_tail_reject_totally() {
    let bytes = fixture();
    for len in 0..SIZE {
        assert!(FullGraph::parse(&bytes[..len]).is_err());
    }
    let mut long = std::vec::Vec::from(bytes);
    long.push(0);
    assert!(FullGraph::parse(&long).is_err());
    for at in (14..16)
        .chain(137..root_v2::HEADER)
        .chain(root_v2::HEADER + CURRENT_GRANTS * root_v2::GRANT_BYTES..SIZE)
    {
        for bit in 0..8 {
            let mut b = bytes;
            b[at] ^= 1 << bit;
            assert!(FullGraph::parse(&b).is_err(), "reserved{at}");
        }
    }
    for role in 0..CURRENT_GRANTS {
        for at in [17, 20, 21, 22, 23] {
            let mut b = bytes;
            b[root_v2::HEADER + role * root_v2::GRANT_BYTES + at] = 1;
            assert!(FullGraph::parse(&b).is_err());
        }
    }
    for at in [0, 8, 10, 12] {
        let mut b = bytes;
        b[at] ^= 0x80;
        assert!(FullGraph::parse(&b).is_err());
    }
    for at in [16, 24, 32, 40, 48, 56, 64] {
        let mut b = bytes;
        b[at..at + 8].fill(0);
        assert!(FullGraph::parse(&b).is_err());
    }
}
#[test]
fn native_aliases_kind_rights_selector_and_extra_roles_never_widen_profile() {
    let bytes = fixture();
    for (i, role) in ROLES.iter().enumerate() {
        let offset = root_v2::HEADER + i * root_v2::GRANT_BYTES;
        for bit in 0..16 {
            let mut b = bytes;
            b[offset + 18..offset + 20].copy_from_slice(&(role.rights ^ (1 << bit)).to_le_bytes());
            assert!(FullGraph::parse(&b).is_err());
        }
        for kind in 0..=9 {
            if kind != role.kind {
                let mut b = bytes;
                b[offset + 16] = kind;
                assert!(FullGraph::parse(&b).is_err());
            }
        }
        let mut b = bytes;
        b[offset..offset + 8].copy_from_slice(&(role.selector + 1).to_le_bytes());
        assert!(FullGraph::parse(&b).is_err());
        if i != 0 {
            let mut b = bytes;
            b[offset + 8..offset + 16].copy_from_slice(&100u64.to_le_bytes());
            assert!(matches!(Bootstrap::parse(&b), Err(Error::Alias)));
        }
    }
    let grants = core::array::from_fn::<_, MAX_GRANTS, _>(|i| Grant {
        selector: i as u64 + 1,
        handle: 100 + i as u64,
        kind: 1,
        rights: 1,
    });
    let b = encode(context(), &grants).unwrap();
    assert_eq!(Bootstrap::parse(&b).unwrap().grants().count(), 24);
    assert!(FullGraph::parse(&b).is_err());
    let b = encode(context(), &grants[..20]).unwrap();
    assert!(FullGraph::parse(&b).is_err());
    let mut b = bytes;
    b[136] = 23;
    assert!(FullGraph::parse(&b).is_err());
}
#[test]
fn native_manifest_has_distinct_abi_profile22_and912_without_legacy_change() {
    let b = manifest_profile(inputs()).unwrap();
    assert_eq!(b.len(), 912);
    assert_eq!(b[48..80], ABI);
    assert_ne!(ABI, root_v2::ABI);
    assert_ne!(ABI, crate::ABI);
    assert_eq!(b[160], 22);
    assert_eq!(b[168..170], 3u16.to_le_bytes());
    assert_eq!(b[170..172], 720u16.to_le_bytes());
    assert_eq!(b[172..174], 3u16.to_le_bytes());
    for (i, role) in ROLES.iter().enumerate() {
        let at = root_v2::MANIFEST_HEADER + i * root_v2::MANIFEST_GRANT_BYTES;
        assert_eq!(&b[at..at + 8], &role.selector.to_le_bytes());
        assert_eq!(b[at + 8], role.kind);
        assert_eq!(b[at + 9], 0);
        assert_eq!(&b[at + 10..at + 12], &role.rights.to_le_bytes());
        assert!(b[at + 12..at + 32].iter().all(|&n| n == 0));
    }
    for field in 0..4 {
        for invalid in [0, u64::MAX] {
            let mut i = inputs();
            i.limits[field] = invalid;
            assert!(manifest_profile(i).is_err());
        }
    }
    let mut i = inputs();
    i.restart_attempts = 9;
    assert!(manifest_profile(i).is_err());
    let mut i = inputs();
    i.restart_window = 0;
    assert!(manifest_profile(i).is_err());
}
#[test]
fn native_catalogue_embeds_exact_legacy_components_but_owns_native_root_contract() {
    let bytes = catalogue_bytes();
    let c = catalogue::Catalogue::decode(&bytes).unwrap();
    assert_eq!(c.base().bytes(), base_bytes());
    assert_eq!((c.root_abi(), c.profile()), (ABI, PROFILE));
    assert_eq!(
        (c.package_a(), c.package_b(), c.package_b_build()),
        ([5; 32], [43; 32], [44; 32])
    );
    assert_eq!(
        (c.package_a_bytes(), c.package_b_bytes()),
        (4097, PACKAGE_MAX_BYTES)
    );
    assert_eq!(c.app_b().limits, base::CHILD_LIMITS);
    assert!(base::Catalogue::decode(&bytes).is_err());
    assert!(catalogue::Catalogue::decode(&bytes[..base::SIZE]).is_err());
    let (a, b) = c.measurement_parts();
    assert_eq!(a.len() + b.len(), catalogue::SIZE - 32);
    assert_eq!(a, &bytes[..catalogue::MEASUREMENT_OFFSET]);
    assert_eq!(b, &bytes[catalogue::MEASUREMENT_OFFSET + 32..]);
}
#[test]
fn native_catalogue_unknown_abi_profiles_roles_lengths_and_package_aliases_fail() {
    let bytes = catalogue_bytes();
    for len in 0..catalogue::SIZE {
        assert!(catalogue::Catalogue::decode(&bytes[..len]).is_err());
    }
    let mut long = std::vec::Vec::from(bytes);
    long.push(0);
    assert!(catalogue::Catalogue::decode(&long).is_err());
    for at in [
        base::SIZE,
        base::SIZE + 8,
        base::SIZE + 10,
        base::SIZE + 12,
        48,
        80,
        base::SIZE + 16,
        base::SIZE + 160,
        base::SIZE + 160 + 72,
        base::SIZE + 160 + 104,
        base::SIZE + 160 + 136,
        base::SIZE + 160 + 137,
    ] {
        let mut b = bytes;
        b[at] ^= 1;
        assert!(catalogue::Catalogue::decode(&b).is_err(), "offset{at}");
    }
    for byte in 0..32 {
        for bit in 0..8 {
            let mut b = bytes;
            b[base::SIZE + 16 + byte] ^= 1 << bit;
            assert!(matches!(
                catalogue::Catalogue::decode(&b),
                Err(catalogue::Error::Abi)
            ));
        }
    }
    for offset in [144, 152] {
        for length in [0, PACKAGE_MAX_BYTES + 1, u64::MAX] {
            let mut b = bytes;
            b[base::SIZE + offset..base::SIZE + offset + 8].copy_from_slice(&length.to_le_bytes());
            assert!(catalogue::Catalogue::decode(&b).is_err());
        }
    }
    for offset in [48, 80, 112] {
        let mut b = bytes;
        b[base::SIZE + offset..base::SIZE + offset + 32].fill(0);
        assert!(catalogue::Catalogue::decode(&b).is_err());
    }
    let mut b = bytes;
    b[base::SIZE + 80..base::SIZE + 112].copy_from_slice(&[5; 32]);
    assert!(catalogue::Catalogue::decode(&b).is_err());
    let mut b = bytes;
    b[base::SIZE + 160 + 144..base::SIZE + 160 + 176].fill(99);
    assert!(catalogue::Catalogue::decode(&b).is_err());
}
#[test]
fn native_catalogue_checks_every_reserved_byte_and_preserves_measurement_mask() {
    let bytes = catalogue_bytes();
    let base_reserved = (14..16)
        .chain(258..264)
        .chain(base::HEADER + base::IMAGES * base::IMAGE_BYTES..base::SIZE);
    let extension_reserved = (base::SIZE + 14..base::SIZE + 16)
        .chain(base::SIZE + 160 + 138..base::SIZE + 160 + 144)
        .chain(base::SIZE + 336 + 138..base::SIZE + 336 + 144)
        .chain(catalogue::BOOT_MODE_OFFSET + 2..catalogue::SIZE);
    for at in base_reserved.chain(extension_reserved) {
        let mut b = bytes;
        b[at] = 1;
        assert!(catalogue::Catalogue::decode(&b).is_err(), "reserved{at}");
    }
    for i in 0..base::IMAGES {
        for at in 138..144 {
            let mut b = bytes;
            b[base::HEADER + i * base::IMAGE_BYTES + at] = 1;
            assert!(catalogue::Catalogue::decode(&b).is_err());
        }
    }
    let mut other = bytes;
    other[catalogue::MEASUREMENT_OFFSET..catalogue::MEASUREMENT_OFFSET + 32].fill(46);
    let a = catalogue::Catalogue::decode(&bytes).unwrap();
    let b = catalogue::Catalogue::decode(&other).unwrap();
    assert_eq!(a.measurement_parts(), b.measurement_parts());
}
