#[test]
fn only_system_managed_has_the_composed_world_extent() {
    for (mode, expected) in [
        (catalogue::BootMode::Standalone, 16_384),
        (catalogue::BootMode::SystemManaged, 32_768),
        (catalogue::BootMode::Recovery, 16_384),
    ] {
        let mut bytes = catalogue_bytes();
        bytes[catalogue::BOOT_MODE_OFFSET..catalogue::BOOT_MODE_OFFSET + 2]
            .copy_from_slice(&(mode as u16).to_le_bytes());
        let decoded = catalogue::Catalogue::decode(&bytes).unwrap();
        assert_eq!(world_ticks(decoded.boot_mode()), expected);
        assert_eq!(
            decoded.base().images().next().unwrap().limits,
            base::CHILD_LIMITS
        );
        assert_eq!(base::CHILD_LIMITS, [16_384, 32, 1, 1]);
    }
}
