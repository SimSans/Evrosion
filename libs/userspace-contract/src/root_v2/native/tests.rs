#[test]
fn native3_mode_and_bad_shell_are_exact_and_cohort_mask_excludes_only_mode_and_measurement() {
    let bytes = catalogue_bytes();
    let mut variants = std::vec::Vec::new();
    for (tag, mode) in [
        (0, catalogue::BootMode::Standalone),
        (1, catalogue::BootMode::SystemManaged),
        (2, catalogue::BootMode::Recovery),
    ] {
        let mut current = bytes;
        current[catalogue::BOOT_MODE_OFFSET..catalogue::BOOT_MODE_OFFSET + 2]
            .copy_from_slice(&(tag as u16).to_le_bytes());
        current[catalogue::MEASUREMENT_OFFSET..catalogue::MEASUREMENT_OFFSET + 32].fill(60 + tag);
        let value = catalogue::Catalogue::decode(&current).unwrap();
        assert_eq!(value.boot_mode(), mode);
        assert_eq!(value.bad_shell().roles, [30; 32]);
        assert_ne!(
            value.bad_shell().image,
            value.base().images().next().unwrap().image
        );
        variants.push(current);
    }
    let a = catalogue::Catalogue::decode(&variants[0]).unwrap();
    for b in &variants[1..] {
        assert_eq!(
            a.cohort_parts(),
            catalogue::Catalogue::decode(b).unwrap().cohort_parts()
        );
    }
    for invalid in [3, 255, u16::MAX] {
        let mut b = bytes;
        b[catalogue::BOOT_MODE_OFFSET..catalogue::BOOT_MODE_OFFSET + 2]
            .copy_from_slice(&invalid.to_le_bytes());
        assert!(matches!(
            catalogue::Catalogue::decode(&b),
            Err(catalogue::Error::BootMode)
        ));
    }
    for at in [
        base::SIZE + 336,
        base::SIZE + 336 + 72,
        base::SIZE + 336 + 104,
        base::SIZE + 336 + 137,
        base::SIZE + 336 + 144,
    ] {
        let mut b = bytes;
        b[at] ^= 1;
        assert!(catalogue::Catalogue::decode(&b).is_err());
    }
    let mut b = bytes;
    b[base::SIZE + 336 + 8..base::SIZE + 336 + 40].fill(10);
    assert!(catalogue::Catalogue::decode(&b).is_err());
    let mut old = fixture();
    old[8..10].copy_from_slice(&2u16.to_le_bytes());
    assert!(FullGraph::parse(&old).is_err());
}
